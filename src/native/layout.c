const Layout *layout_for(const char *program)
{
    if (strcmp(program, "MAGIC") == 0)
        return &LAYOUT_MAGIC;
    if (strcmp(program, "DUEL") == 0)
        return &LAYOUT_DUEL;
    return NULL;
}
