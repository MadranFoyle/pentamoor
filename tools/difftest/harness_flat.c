/*
 * harness_flat.c - run one *lifted* function (tools/lift) on one test vector.
 *
 * The same line protocol as harness.c (see there), so run_vectors.py drives it unchanged:
 *     run_vectors.py --harness tools/difftest/build/harness-flat vector.json
 * The difference is the memory: lifted code reads and writes raw guest addresses, so the guest address space is one flat
 * array G, and there is no per-byte "was it defined" tracking to catch reads of memory the vector does not provide.
 * Instead every vector is run twice, with the undefined memory filled with two different bytes, and the runs must agree
 * on the return value, every written byte and every call made: if they do not, the function read something the vector
 * does not define.
 *
 * The low 16 MB of the guest (the program image) sit in G at their own addresses. The 1 MB blocks above that which a
 * vector touches (the heap, the stack of the thread the function was recorded on) are folded in behind them (lift_xl),
 * so a recorded stack pointer can be used as it is and pointers into the stack compare equal to the recording's. Writes
 * to the stack frame are not part of the compared output; every other byte the function stores to is, whatever value
 * it stores (the lifted code reports each store; a changed-bytes diff would miss a store of the value already there).
 * The function must be generated by tools/lift/gen_handlers.py (the LIFTED and LIFT_CALLEES tables).
 */
#include <setjmp.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "lift_rt.h"
#include "lift_tables.h"

#define LOW_SIZE 0x01000000u /* guest addresses below this are in G as they are */
#define HIGH_BLOCKS 16       /* 1 MB blocks above LOW_SIZE that can be folded in */
#define GSIZE (LOW_SIZE + HIGH_BLOCKS * 0x100000u)
#define STACK_LO 0x00f00000u /* with no recorded stack pointer, the stack is the top of the low memory */
#define STACK_TOP 0x00fff000u
#define FRAME_BELOW 0x200000u /* what the recorder counts as the stack frame: this far below ESP, up to the arguments */
#define MAX_ARGS 32
#define MAX_REGIONS 4096
#define MAX_CALLS 8192

uint8_t *G;

typedef struct {
    uint32_t addr;
    uint8_t *bytes;
    size_t len;
} Blob;

typedef struct {
    uint32_t addr, ret;
    int nargs;
    uint32_t args[MAX_ARGS];
    Blob *writes;
    int nwrites;
} Mock;

typedef struct {
    int made;
    uint32_t addr[MAX_CALLS];
    int nargs[MAX_CALLS];
    uint32_t args[MAX_CALLS][MAX_ARGS];
} CallLog;

static Blob *blobs;
static int nblobs;
static Mock *mocks;
static int nmocks;
static uint32_t read_addr[8192], read_len[8192];
static int nread_req;
static uint32_t high_block[HIGH_BLOCKS]; /* guest address >> 20 of each folded-in block */
static int nhigh;
static uint32_t stack_ptr;
static int have_stack_ptr;
static CallLog L;
static int next_mock;
static jmp_buf bail;
static char error_text[256];

static void die(const char *msg, const char *detail)
{
    printf("error %s%s%s\n", msg, detail ? ": " : "", detail ? detail : "");
    exit(3);
}

static uint32_t parse_u32(const char *s)
{
    char *end;
    unsigned long v;
    if (!s)
        die("missing number", NULL);
    v = strtoul(s, &end, 0);
    if (*end)
        die("bad number", s);
    return (uint32_t)v;
}

static int hexval(int c)
{
    return c >= '0' && c <= '9' ? c - '0' : c >= 'a' && c <= 'f' ? c - 'a' + 10 : c >= 'A' && c <= 'F' ? c - 'A' + 10 : -1;
}

static uint8_t *parse_hex(const char *s, size_t *len)
{
    size_t n = s ? strlen(s) : 0, i;
    uint8_t *out;
    if (n == 0 || n % 2)
        die("bad hex bytes", s);
    out = malloc(n / 2);
    for (i = 0; i < n / 2; i++) {
        int hi = hexval(s[2 * i]), lo = hexval(s[2 * i + 1]);
        if (hi < 0 || lo < 0)
            die("bad hex bytes", s);
        out[i] = (uint8_t)(hi << 4 | lo);
    }
    *len = n / 2;
    return out;
}

static void map_range(uint32_t addr, size_t len);

#ifdef LIFT_COVERAGE
/* The addresses of the instructions executed, appended to the file named by $FLAT_COV when the harness exits. */
static uint32_t *cov;
static size_t ncov, capcov;
void lift_cov(uint32_t a)
{
    size_t i;
    for (i = 0; i < ncov; i++)
        if (cov[i] == a)
            return;
    if (ncov == capcov)
        cov = realloc(cov, sizeof(uint32_t) * (capcov = capcov ? capcov * 2 : 1024));
    cov[ncov++] = a;
}
static void dump_cov(void)
{
    const char *path = getenv("FLAT_COV");
    FILE *f = path ? fopen(path, "a") : NULL;
    size_t i;
    if (!f)
        return;
    for (i = 0; i < ncov; i++)
        fprintf(f, "%x\n", cov[i]);
    fclose(f);
}
#endif

uint32_t lift_xl(uint32_t a)
{
    int i;
    if (a < LOW_SIZE)
        return a;
    for (i = 0; i < nhigh; i++)
        if (high_block[i] == a >> 20)
            return LOW_SIZE + (uint32_t)i * 0x100000u + (a & 0xfffffu);
    snprintf(error_text, sizeof(error_text), "access to 0x%08x, in memory the vector does not provide", a);
    longjmp(bail, 1);
}

/* Make sure every block of [addr, addr + len) can be addressed. */
static void map_range(uint32_t addr, size_t len)
{
    uint64_t end = (uint64_t)addr + (len ? len : 1), b;
    int i;
    if (end > 0x100000000ull)
        die("address range wraps around the 32-bit address space", NULL);
    for (b = addr >> 20; b <= (end - 1) >> 20; b++) {
        if (b < (LOW_SIZE >> 20))
            continue;
        for (i = 0; i < nhigh && high_block[i] != b; i++)
            ;
        if (i == nhigh) {
            if (nhigh >= HIGH_BLOCKS)
                die("the vector touches more distinct 1 MB blocks than the flat harness can fold in", NULL);
            high_block[nhigh++] = (uint32_t)b;
        }
    }
}

#ifdef LIFT_UNDEF_CHECK
static uint8_t *DEF;
static int undef_reports;
#endif
static uint8_t *WRT; /* bytes the lifted function stored to, whatever the value */
void lift_chk_write(uint32_t a, uint32_t n)
{
    uint32_t x = lift_xl(a);
    memset(WRT + x, 1, n);
#ifdef LIFT_UNDEF_CHECK
    memset(DEF + x, 1, n);
#endif
}
#ifdef LIFT_UNDEF_CHECK
void lift_chk_read(uint32_t a, uint32_t n)
{
    uint32_t i, x = lift_xl(a);
    for (i = 0; i < n; i++)
        if (!DEF[x + i] && undef_reports < 6) {
            fprintf(stderr, "undefined read of %u bytes at 0x%08x\n", n, a);
            undef_reports++;
            break;
        }
}
#endif

/* Store bytes into the guest, as setup or as a replayed callee's write (neither counts as the function's own stores). */
static void put(uint32_t addr, const uint8_t *b, size_t len)
{
    size_t i;
    map_range(addr, len);
    for (i = 0; i < len; i++) { /* a byte at a time: a block boundary may fall inside */
        uint32_t x = lift_xl(addr + (uint32_t)i);
        G[x] = b[i];
#ifdef LIFT_UNDEF_CHECK
        DEF[x] = 1;
#endif
    }
}

void lift_bad_jump(uint32_t from)
{
    snprintf(error_text, sizeof(error_text), "the jump at 0x%08x indexed past its table", from);
    longjmp(bail, 1);
}

LiftRegs lift_in, lift_out;   /* the flat harness has no registers to give: lifted code starts from zero */
__thread uint32_t lift_ret_edx = 0xcdcdcdcdu;
__thread uint64_t lift_x87[8];
__thread unsigned lift_xt;
