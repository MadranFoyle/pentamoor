#!/usr/bin/env python3
"""
check_tree.py - fail if anything that looks like decompiler output, or like a table made from it, is tracked in the repository (or is in a release archive).

Pentamoor has no code that was generated from the game, and a decompiler's output is exactly that. Everything here is a heuristic, so that it cannot creep back in by accident:

  * a folder named like the ones the upstream project's decompilation lived in (magic/, duel/, deck/, deckdll/, statwin/, magsnd/, magvid/, scripts/, symbols/ at the top of the
    repository), or named ghidra, decompiled or decomp anywhere;
  * a file named like what a decompiler run leaves behind: function_index.csv, symbols.csv, source_mapping.csv, *_unified.c, *_unified.h, *_all.c;
  * a C, C++ or Java file that says it was generated by Ghidra or is a decompiled source, that calls functions the way decompiled code does (FUN_00401000(...)), or that has
    a decompiler's local names (param_1, local_14, uVar2, `undefined4`); a CSV or TSV table with that header or hundreds of such names. (A comment that names an address
    as DAT_00401000 is only a label and is not looked for.)

    python3 tools/release/check_tree.py            # the files git tracks, from the repository this file is in
    python3 tools/release/check_tree.py --root DIR # every file under DIR (an unpacked archive)
"""
import argparse
import os
import re
import subprocess
import sys

REMOVED_TOP = {"magic", "duel", "deck", "deckdll", "statwin", "magsnd", "magvid", "scripts", "symbols"}
FORBIDDEN_DIRS = {"ghidra", "decompiled", "decomp"}
FORBIDDEN_NAMES = {"function_index.csv", "symbols.csv", "source_mapping.csv"}
FORBIDDEN_NAME_PATTERNS = (re.compile(r".*_unified\.(c|h)$"), re.compile(r".*_all\.c$"))
CONTENT_SUFFIXES = (".c", ".h", ".cc", ".cpp", ".hpp", ".inc", ".java", ".csv", ".tsv")
MAX_BYTES = 64 << 20
HEADER = re.compile(rb"Generated by Ghidra|Ghidra Decompiler|Decompiled ANSI C|Decompiled C Source|decompiled with Ghidra", re.I)
DECOMPILER_NAMES = re.compile(rb"\b(?:FUN|DAT|LAB|PTR|UNK|SUB|EXT)_[0-9a-f]{8}\b")
CALLS = re.compile(rb"\b(?:thunk_)?FUN_[0-9a-f]{8}\s*\(")
LOCALS = re.compile(rb"\b(?:param_\d+|local_[0-9a-f]+|[a-z]{1,3}Var\d+)\b")
UNDEFINED = re.compile(rb"\bundefined[1248]?\b")
CODE_SUFFIXES = (".c", ".h", ".cc", ".cpp", ".hpp", ".inc", ".java")


def problems_for_path(path):
    """What is wrong with a tracked path alone (its folders and its name), as a list of sentences."""
    parts = path.split("/")
    out = []
    if len(parts) > 1 and parts[0] in REMOVED_TOP:
        out.append(f"{path}: in a top-level folder named like the removed decompilation ({parts[0]}/)")
    if any(p.lower() in FORBIDDEN_DIRS for p in parts[:-1]):
        out.append(f"{path}: in a folder named for a decompiler's output")
    base = parts[-1]
    if base in FORBIDDEN_NAMES or any(p.match(base) for p in FORBIDDEN_NAME_PATTERNS):
        out.append(f"{path}: named like a decompiler run's output")
    return out


def problems_for_content(path, data):
    """What is wrong with the contents of a source or table file (bytes), as a list of sentences."""
    if not path.lower().endswith(CONTENT_SUFFIXES):
        return []
    out = []
    if HEADER.search(data[:4000]):
        out.append(f"{path}: its header says it is decompiler output")
    if path.lower().endswith(CODE_SUFFIXES):
        if len(CALLS.findall(data)) >= 5:
            out.append(f"{path}: calls like FUN_00401000(...), as decompiled code does")
        if len(LOCALS.findall(data)) >= 15:
            out.append(f"{path}: decompiler-style locals (param_1, local_14, uVar2)")
        if len(UNDEFINED.findall(data)) >= 5:
            out.append(f"{path}: decompiler-style `undefined` types")
    elif len(DECOMPILER_NAMES.findall(data)) >= 100:
        out.append(f"{path}: hundreds of decompiler-style names (FUN_00401000, DAT_00401000, ...)")
    return out


def check_files(root, paths):
    problems = []
    for p in paths:
        problems += problems_for_path(p)
        full = os.path.join(root, p)
        try:
            if not os.path.isfile(full) or os.path.islink(full) or os.path.getsize(full) > MAX_BYTES:
                continue
            with open(full, "rb") as f:
                data = f.read()
        except OSError:
            continue
        problems += problems_for_content(p, data)
    return problems


def tracked_files(repo):
    out = subprocess.run(["git", "ls-files", "-z"], cwd=repo, check=True, stdout=subprocess.PIPE).stdout
    return sorted(p for p in out.decode("utf-8", "surrogateescape").split("\0") if p)


def all_files(root):
    found = []
    for dirpath, _, filenames in os.walk(root):
        for f in filenames:
            found.append(os.path.relpath(os.path.join(dirpath, f), root).replace(os.sep, "/"))
    return sorted(found)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--root", help="check every file under this folder instead of what git tracks")
    args = ap.parse_args()
    if args.root:
        root, paths = args.root, all_files(args.root)
    else:
        root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
        paths = tracked_files(root)
    problems = check_files(root, paths)
    print(f"check_tree: {len(paths)} files looked at")
    if problems:
        print("\nLOOKS LIKE DECOMPILER OUTPUT:\n  " + "\n  ".join(problems))
        sys.exit(1)
    print("check_tree: no decompiler output")


if __name__ == "__main__":
    main()
